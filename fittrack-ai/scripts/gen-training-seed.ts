// Generates the exercise and track seed SQL from the bundled library, so the two never drift.
// Run with: deno run scripts/gen-training-seed.ts > supabase/migrations/20261117001000_seed_training.sql
import { EXERCISES, TRACKS, trackExerciseId } from '../src/domain/training/exercises.ts';

const q = (s: string | null) => (s === null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => `array[${xs.map(q).join(', ')}]::text[]`;
const lines: string[] = [];
lines.push('-- Generated by scripts/gen-training-seed.ts from src/domain/training/exercises.ts. Do not edit by hand.');
lines.push('-- Shared library rows (user_id null): readable by everyone signed in, writable by nobody through the API.');
lines.push('-- demo_variants are all null: no licensed demo media ships yet, so the app shows its illustrated figures.');
lines.push('insert into public.exercises (id, user_id, slug, name, kind, default_target, cues, progression, is_pair, form_video_url, demo_variants) values');
lines.push(EXERCISES.map((e) => `  (${q(e.id)}, null, ${q(e.slug)}, ${q(e.name)}, ${q(e.kind)}, ${e.target ?? 'null'}, ${arr(e.cues)}, ${q(e.progression)}, ${e.pair}, ${q(`https://www.youtube.com/results?search_query=${encodeURIComponent(e.videoQuery)}`)}, '{"female": null, "male": null, "pair": null}'::jsonb)`).join(',\n'));
lines.push('on conflict (id) do update set name = excluded.name, kind = excluded.kind, default_target = excluded.default_target, cues = excluded.cues, progression = excluded.progression, is_pair = excluded.is_pair, form_video_url = excluded.form_video_url;');
lines.push('');
lines.push('insert into public.workout_tracks (id, user_id, slug, name, description, sets_per_move, rest_seconds, is_couples) values');
lines.push(Object.values(TRACKS).map((t) => `  (${q(t.id)}, null, ${q(t.slug)}, ${q(t.name)}, ${q(t.description)}, ${t.setsPerMove}, ${t.restSeconds}, ${t.couples})`).join(',\n'));
lines.push('on conflict (id) do update set name = excluded.name, description = excluded.description, sets_per_move = excluded.sets_per_move, rest_seconds = excluded.rest_seconds, is_couples = excluded.is_couples;');
lines.push('');
lines.push('insert into public.track_exercises (id, user_id, track_id, exercise_id, position, sets, target, level) values');
const rows: string[] = [];
for (const t of Object.values(TRACKS)) {
  t.moves.forEach((slug, i) => {
    const e = EXERCISES.find((x) => x.slug === slug)!;
    rows.push(`  (${q(trackExerciseId(t.slug, i))}, null, ${q(t.id)}, ${q(e.id)}, ${i}, ${t.setsPerMove}, ${e.target ?? 'null'}, ${e.defaultLevel ?? 0})`);
  });
}
lines.push(rows.join(',\n'));
lines.push('on conflict (id) do update set exercise_id = excluded.exercise_id, position = excluded.position, sets = excluded.sets, target = excluded.target, level = excluded.level;');
console.log(lines.join('\n'));
